// 分野は開くたびに順に変える（最初の分野は毎回ちがう）
let turn = Math.floor(Math.random() * 4)

/** 次の分野（0 仕事・1 家のこと・2 人づきあい・3 体調） */
export function nextDomain(): number {
  turn = (turn + 1) % 4
  return turn
}

/**
 * 見本を1つ選ぶ。question があればその問いの例、なければ欄（where / first）か枠の例。
 * domain を渡すと、その分野の例（同じ紙の欄どうしで分野をそろえる時）
 */
export function exampleFor(opts: { question?: string; field?: 'where' | 'first'; frame: FrameNo }, domain = nextDomain()): string | undefined {
  const list = (opts.question && BY_QUESTION[opts.question]) || (opts.field && BY_FIELD[opts.field]) || BY_FIELD[`frame${opts.frame}`]
  return list?.[domain]
}
